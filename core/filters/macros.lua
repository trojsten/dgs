--[[
`core/latex/math.tex` expanded to plain LaTeX, so that any renderer can read what we ship.

MathJax takes a macro table, but not this one. `\FDiff` is declared `e{^_} t[ m` -- an xparse
*embellishment* argument, which collects a `^` group and a `_` group in either order and may
have neither -- and it is written 951 times. `\Int` takes two leading optionals, `\Coord` splits
a `;`-separated list at the TeX level, and MathJax's `macros` config can express one leading
optional argument and nothing else.

So the expansion happens here instead, and what reaches the page is plain LaTeX: MathJax renders
it today and KaTeX or MathML could tomorrow, which a MathJax-specific configuration would have
foreclosed.

The table is `macros-table.lua`, generated by `python -m core.html.macros`. Nothing here knows
any macro by name; it knows four argument shapes.
--]]

local table_path = (os.getenv('DGS_ROOT') or '.') .. '/core/filters/macros-table.lua'
local MACROS = dofile(table_path).macros

--- Read a `{…}` group at `position`, respecting nesting. Returns the body and what follows.
local function group(text, position)
    if text:sub(position, position) ~= '{' then
        return nil
    end
    local depth, index = 0, position
    while index <= #text do
        local character = text:sub(index, index)
        if character == '\\' then
            index = index + 1          -- an escaped brace is not a brace
        elseif character == '{' then
            depth = depth + 1
        elseif character == '}' then
            depth = depth - 1
            if depth == 0 then
                return text:sub(position + 1, index - 1), index + 1
            end
        end
        index = index + 1
    end
    return nil
end

--- Read a `[…]` optional argument, respecting nesting.
local function optional(text, position)
    if text:sub(position, position) ~= '[' then
        return nil
    end
    local depth, index = 0, position
    while index <= #text do
        local character = text:sub(index, index)
        if character == '\\' then
            index = index + 1
        elseif character == '[' then
            depth = depth + 1
        elseif character == ']' then
            depth = depth - 1
            if depth == 0 then
                return text:sub(position + 1, index - 1), index + 1
            end
        end
        index = index + 1
    end
    return nil
end

--- Skip whitespace, which TeX does between a macro and its arguments.
local function skip(text, position)
    local _, stop = text:find('^%s*', position)
    return stop + 1
end

--- Substitute `#1`…`#9`, keeping a macro name from running into what follows it.
-- `\left\lvert#1\right\rvert` filled with `v` gives `\left\lvertv…`, which is a control
-- word nobody defined. TeX would need a space there and so does this.
local function fill(template, arguments)
    return (template:gsub('()#(%d)', function(position, index)
        local argument = arguments[tonumber(index)] or ''
        local before = template:sub(1, position - 1)
        if argument:match('^%a') and before:match('\\%a+$') then
            return ' ' .. argument
        end
        return argument
    end))
end

--- One macro at `position`, expanded. Returns the replacement and the position after it.
local function expand_one(text, name, position)
    local shape = MACROS[name]
    if not shape then
        return nil
    end
    local kind = shape[1]

    if kind == 'symbol' then
        return shape[2], position
    end

    if kind == 'args' then
        local count, template = shape[2], shape[3]
        local arguments, cursor = {}, position
        for _ = 1, count do
            cursor = skip(text, cursor)
            local body, after = group(text, cursor)
            if not body then
                return nil
            end
            arguments[#arguments + 1] = body
            cursor = after
        end
        return fill(template, arguments), cursor
    end

    if kind == 'diff' then
        -- `e{^_}`: a `^` group and a `_` group, in either order, both optional. `\FDiff^2_x{H}`
        -- and `\FDiff_x^2{H}` are the same thing, and plain `\FDiff{H}` is the common case.
        local symbol = shape[2]
        local superscript, subscript, cursor = nil, nil, position
        for _ = 1, 2 do
            local mark = text:sub(cursor, cursor)
            if mark == '^' or mark == '_' then
                local body, after = group(text, cursor + 1)
                if not body then
                    -- a single token embellishment: `\FDiff^2{H}`
                    body = text:sub(cursor + 1, cursor + 1)
                    after = cursor + 2
                end
                if mark == '^' then
                    superscript = body
                else
                    subscript = body
                end
                cursor = after
            end
        end
        -- the `t[` guard raises a ClassError in LaTeX on the retired `\FDiff[power]` form; here
        -- leaving it unexpanded is enough, because the build refuses an unexpanded macro anyway
        if text:sub(cursor, cursor) == '[' then
            return nil
        end
        cursor = skip(text, cursor)
        local body, after = group(text, cursor)
        if not body then
            return nil
        end
        local out = symbol
        if superscript then
            out = out .. '^{' .. superscript .. '}'
        end
        if subscript then
            out = out .. '_{' .. subscript .. '}'
        end
        return out .. ' ' .. body, after
    end

    if kind == 'opt' then
        local optionals, mandatory, template = shape[2], shape[3], shape[4]
        local arguments, cursor = {}, position
        for _ = 1, optionals do
            local body, after = optional(text, cursor)
            arguments[#arguments + 1] = body or ''
            if body then
                cursor = after
            end
        end
        for _ = 1, mandatory do
            cursor = skip(text, cursor)
            local body, after = group(text, cursor)
            if not body then
                return nil
            end
            arguments[#arguments + 1] = body
            cursor = after
        end
        return fill(template, arguments), cursor
    end

    if kind == 'splitlist' then
        -- `\Coord{a; b}` -- the list is split in TeX by `>{\SplitList{;}}`, which has no
        -- counterpart anywhere outside LaTeX
        local separator, left, right = shape[2], shape[3], shape[4]
        local cursor = skip(text, position)
        local body, after = group(text, cursor)
        if not body then
            return nil
        end
        local pieces = {}
        for piece in (body .. separator):gmatch('(.-)' .. separator) do
            pieces[#pieces + 1] = piece:gsub('^%s+', ''):gsub('%s+$', '')
        end
        return left .. table.concat(pieces, separator .. ' ') .. right, after
    end

    return nil
end

--- Expand every known macro, innermost last: the pass repeats while anything changed, so a
--- macro produced by another macro's template is expanded too.
local function expand(text)
    for _ = 1, 8 do
        local out, position, changed = {}, 1, false
        while position <= #text do
            local name, after = text:match('^\\([A-Za-z]+)()', position)
            if name and MACROS[name] then
                local replacement, tail = expand_one(text, name, after)
                if replacement then
                    out[#out + 1] = replacement
                    position = tail
                    changed = true
                else
                    out[#out + 1] = text:sub(position, after - 1)
                    position = after
                end
            elseif name then
                out[#out + 1] = text:sub(position, after - 1)
                position = after
            else
                out[#out + 1] = text:sub(position, position)
                position = position + 1
            end
        end
        text = table.concat(out)
        if not changed then
            break
        end
    end
    return text
end

return {
    {Math = function(element)
        local expanded = expand(element.text)
        if expanded ~= element.text then
            element.text = expanded
            return element
        end
    end},
}
