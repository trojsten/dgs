--[[
siunitx, rewritten into maths MathJax can read.

MathJax has an mhchem extension and no siunitx one -- none exists -- and the sources make some
9200 siunitx calls inside maths. So `\qty{3}{\metre\per\second}` has to become
`3\,\mathrm{m}/\mathrm{s}` before it reaches the page, reproducing what `core/latex/siunitx.tex`
configures siunitx to print.

**It is a filter over `Math` nodes, which is the whole argument for doing it here.** Pandoc has
already decided what is maths: a `\qty` inside a fenced code block, a URL or an image path is a
different node type and this cannot reach it. The alternative -- a regex bank over the Markdown
before pandoc reads it -- would have to re-detect all of that, one line at a time, and would get
it wrong in exactly the ways `core/filters/spacing.lua`'s comment describes.

The vocabulary and the settings are in `siunitx-table.lua`, generated by
`python -m core.html.siunitx` from `core/latex/siunitx.tex`. Nothing here is a unit.
--]]

local table_path = (os.getenv('DGS_ROOT') or '.') .. '/core/filters/siunitx-table.lua'
local T = dofile(table_path)

local S = T.settings

--- Wrap a unit symbol so it sets upright, which is what a unit is.
-- A symbol that is already a macro or already carries markup is passed through: `\Omega`,
-- `\text{°}C` and `\textit{g}` all know what they want to look like.
local function upright(symbol)
    if symbol:match('^[A-Za-z]+$') then
        return '\\mathrm{' .. symbol .. '}'
    end
    return symbol
end

--- Split a unit expression into tokens: `\kilo\gram\per\second` -> kilo, gram, per, second.
local function tokenise(unit)
    local tokens = {}
    for name, argument in unit:gmatch('\\(%a+)%s*(%b{})') do
        tokens[#tokens + 1] = {name = name, argument = argument:sub(2, -2)}
    end
    -- the loop above only catches macros that take an argument; do it properly in one pass
    tokens = {}
    local position = 1
    while position <= #unit do
        local name, after = unit:match('^\\(%a+)()', position)
        if name then
            local token = {name = name}
            if T.powers[name] == 0 then
                local argument, tail = unit:match('^%s*(%b{})()', after)
                if argument then
                    token.argument = argument:sub(2, -2)
                    after = tail
                end
            end
            tokens[#tokens + 1] = token
            position = after
        else
            -- anything that is not a macro -- a literal unit under `forbid-literal-units=false`
            local literal, after_literal = unit:match('^([^\\]+)()', position)
            if not literal then break end
            if literal:match('%S') then
                tokens[#tokens + 1] = {literal = literal}
            end
            position = after_literal
        end
    end
    return tokens
end

--- One factor of a unit expression: a symbol, its power, and which side of the solidus it is on.
local function factors(unit)
    local out, pending_prefix, denominator, pending_power = {}, '', false, nil
    for _, token in ipairs(tokenise(unit)) do
        local name = token.name
        if token.literal then
            out[#out + 1] = {symbol = '\\mathrm{' .. token.literal:gsub('^%s+', ''):gsub('%s+$', '')
                                      .. '}', power = 1, denominator = denominator}
        elseif name == 'per' then
            denominator = true
        elseif T.prefix_powers[name] then
            pending_power = T.prefix_powers[name]
        elseif T.powers[name] then
            if #out > 0 then
                out[#out].power = T.powers[name]
            end
        elseif T.powers[name] == 0 then
            if #out > 0 then
                out[#out].power = tonumber(token.argument) or token.argument
            end
        elseif T.prefixes[name] then
            pending_prefix = pending_prefix .. T.prefixes[name]
        else
            local resolved = {name}
            if T.aliases[name] then
                resolved = T.aliases[name]
            end
            for _, part in ipairs(resolved) do
                if part == 'per' then
                    denominator = true
                elseif T.prefixes[part] then
                    pending_prefix = pending_prefix .. T.prefixes[part]
                else
                    local symbol = T.units[part]
                    if not symbol then
                        return nil, part
                    end
                    out[#out + 1] = {
                        symbol = upright(pending_prefix .. symbol),
                        power = pending_power or 1,
                        denominator = denominator,
                    }
                    pending_prefix, pending_power = '', nil
                end
            end
        end
    end
    return out
end

local function with_power(factor)
    if factor.power == 1 then
        return factor.symbol
    end
    return factor.symbol .. '^{' .. tostring(factor.power) .. '}'
end

--- A unit expression, printed the way `\sisetup{per-mode=...}` asks for.
local function render_unit(unit, per_mode)
    local parsed, unknown = factors(unit)
    if not parsed then
        return nil, unknown
    end
    per_mode = per_mode or S['per-mode']
    local top, bottom = {}, {}
    for _, factor in ipairs(parsed) do
        local target = factor.denominator and bottom or top
        target[#target + 1] = factor
    end

    local product = S['inter-unit-product']
    local function join(list, negate)
        local pieces = {}
        for _, factor in ipairs(list) do
            if negate then
                local power = factor.power
                pieces[#pieces + 1] = factor.symbol .. '^{-' .. tostring(power) .. '}'
            else
                pieces[#pieces + 1] = with_power(factor)
            end
        end
        return table.concat(pieces, product)
    end

    if #bottom == 0 then
        return join(top, false)
    end
    if per_mode == 'reciprocal' then
        local all = join(top, false)
        local negated = join(bottom, true)
        return (all == '' and negated) or (all .. product .. negated)
    end
    -- `symbol`, the default here: a solidus, and the denominator bracketed when it has more
    -- than one factor so that `J/(K kg)` cannot be read as `J/K * kg`
    local numerator = #top > 0 and join(top, false) or '1'
    local denominator = join(bottom, false)
    if #bottom > 1 then
        denominator = '\\left(' .. denominator .. '\\right)'
    end
    return numerator .. '/' .. denominator
end

--- Digits, grouped the way `group-separator` and `group-minimum-digits` ask for.
-- Walked from the right rather than reversed and gsubbed: reversing the string reverses the
-- separator with it, which turned `10690` into `10,\690`.
local function group(digits)
    if #digits < S['group-minimum-digits'] then
        return digits
    end
    local pieces, count = {}, 0
    for index = #digits, 1, -1 do
        pieces[#pieces + 1] = digits:sub(index, index)
        count = count + 1
        if count % 3 == 0 and index > 1 then
            pieces[#pieces + 1] = '\1'
        end
    end
    local ordered = {}
    for index = #pieces, 1, -1 do
        ordered[#ordered + 1] = pieces[index]
    end
    return (table.concat(ordered):gsub('\1', S['group-separator']))
end

--- A number, printed as siunitx prints it under `core/latex/siunitx.tex`.
local function render_number(number)
    number = number:gsub('^%s+', ''):gsub('%s+$', '')
    local body, exponent = number:match('^(.-)[eE]([-+]?%d+)$')
    if not exponent then
        body = number
    end
    local sign, digits, fraction = body:match('^([-+]?)(%d*)%.?(%d*)$')
    if not sign then
        -- not a plain number: `parse-numbers=false` territory, passed through as written
        return number
    end
    local rendered = sign .. group(digits) .. (#fraction > 0 and ('.' .. fraction) or '')
    if not exponent then
        return rendered
    end
    -- a bare exponent has no mantissa to print: siunitx sets `\num{e-4}` as `10^{-4}`
    if #digits == 0 and #fraction == 0 then
        return '10^{' .. tostring(tonumber(exponent)) .. '}'
    end
    return rendered .. S['exponent-product'] .. '10^{' .. tostring(tonumber(exponent)) .. '}'
end

--- `[per-mode = symbol, parse-numbers = false]` -> a table.
local function options(raw)
    local parsed = {}
    if not raw then
        return parsed
    end
    for key, value in raw:gmatch('([%w%-]+)%s*=%s*([%w%-]+)') do
        parsed[key] = value
    end
    return parsed
end

local unknown_units = {}

local function quantity(number, unit, raw_options)
    local option = options(raw_options)
    local rendered, unknown = render_unit(unit, option['per-mode'])
    if not rendered then
        unknown_units[unknown] = true
        return nil
    end
    if number == nil then
        return rendered
    end
    local value = option['parse-numbers'] == 'false' and number or render_number(number)
    return value .. S['number-unit-product'] .. rendered
end

--- Every siunitx macro the sources write, rewritten in one pass over a maths string.
local function rewrite(text)
    -- two-argument: \qty, \SI
    for _, macro in ipairs({'qty', 'SI'}) do
        text = text:gsub('\\' .. macro .. '(%b[])(%b{})(%b{})', function(o, n, u)
            return quantity(n:sub(2, -2), u:sub(2, -2), o:sub(2, -2)) or (o .. n .. u)
        end)
        text = text:gsub('\\' .. macro .. '(%b{})(%b{})', function(n, u)
            return quantity(n:sub(2, -2), u:sub(2, -2), nil) or (n .. u)
        end)
    end
    -- one-argument units: \unit, \si
    for _, macro in ipairs({'unit', 'si'}) do
        text = text:gsub('\\' .. macro .. '(%b[])(%b{})', function(o, u)
            return quantity(nil, u:sub(2, -2), o:sub(2, -2)) or (o .. u)
        end)
        text = text:gsub('\\' .. macro .. '(%b{})', function(u)
            return quantity(nil, u:sub(2, -2), nil) or u
        end)
    end
    -- one-argument numbers: \num
    text = text:gsub('\\num(%b[])(%b{})', function(_, n) return render_number(n:sub(2, -2)) end)
    text = text:gsub('\\num(%b{})', function(n) return render_number(n:sub(2, -2)) end)
    -- angles
    text = text:gsub('\\ang(%b[])(%b{})', function(_, a)
        return render_number(a:sub(2, -2)) .. '^\\circ'
    end)
    text = text:gsub('\\ang(%b{})', function(a) return render_number(a:sub(2, -2)) .. '^\\circ' end)
    -- ranges and lists, which repeat the unit on both ends by `range-units`/`list-units`
    text = text:gsub('\\qtyrange(%b[]?)(%b{})(%b{})(%b{})', function(_, a, b, u)
        local first = quantity(a:sub(2, -2), u:sub(2, -2), nil)
        local second = quantity(b:sub(2, -2), u:sub(2, -2), nil)
        return first and (first .. S['range-phrase'] .. second)
    end)
    text = text:gsub('\\qtyrange(%b{})(%b{})(%b{})', function(a, b, u)
        local first = quantity(a:sub(2, -2), u:sub(2, -2), nil)
        local second = quantity(b:sub(2, -2), u:sub(2, -2), nil)
        return first and (first .. S['range-phrase'] .. second)
    end)
    text = text:gsub('\\numrange(%b{})(%b{})', function(a, b)
        return render_number(a:sub(2, -2)) .. S['range-phrase'] .. render_number(b:sub(2, -2))
    end)
    return text
end

local function walk(element)
    local rewritten = rewrite(element.text)
    if rewritten ~= element.text then
        element.text = rewritten
        return element
    end
end

return {
    {Math = walk, RawInline = function(element)
        if element.format == 'tex' then
            element.text = rewrite(element.text)
            return element
        end
    end},
    {Pandoc = function(doc)
        local missing = {}
        for name in pairs(unknown_units) do
            missing[#missing + 1] = name
        end
        if #missing > 0 then
            table.sort(missing)
            error('siunitx.lua: no symbol for \\' .. table.concat(missing, ', \\')
                  .. ' -- add it to `core/html/siunitx.py` and regenerate', 0)
        end
        return doc
    end},
}
