# --------------------------------------------------------------------------- lookup

def index() -> dict[tuple[str, str], Entry]:
    """
    Every name an author may write, keyed by `(kind, name)`.

    Keyed by the pair and not by the name alone because several names mean different things in
    different places and the right answer depends on where the cursor is: `unit` is a filter, an
    attribute **and** a `values:` key; `mag` and `eq` are each two of those; `plural` is both a
    filter and a global in a `.jtex`. The editor knows which it found -- that is what `data-ref`
    carries -- so it asks for the pair.
    """
    built = {}
    for entry in REFERENCE:
        for name in entry.names:
            built[(entry.kind, name)] = entry
    return built


def lookup(name: str, *, kind: str | None = None, env: str | None = None) -> Entry | None:
    """One entry, or `None`. With no `kind`, the first that matches in document order."""
    for entry in REFERENCE:
        if name not in entry.names:
            continue
        if kind is not None and entry.kind != kind:
            continue
        if env is not None and entry.env != env:
            continue
        return entry
    return None


def as_json() -> dict:
    """
    The whole table in the shape `/api/reference` serves and the editor's hover reads.

    Keyed `"<kind>:<name>"`, which is exactly what `highlight.js` puts in `data-ref`, so the
    front end does one dictionary lookup and no parsing.
    """
    payload = {}
    for entry in REFERENCE:
        # A Jinja builtin is *written* with a pipe, so `highlight.js` cannot tell it from one of
        # ours and asks for `filter:indent`. Answering under both keys is the whole reason the
        # builtins are in the table: a hover that goes blank on `|indent` -- which 16 sources
        # write, and which is how an equation goes inside a list item -- reads as broken.
        keys = ('filter', entry.kind) if entry.kind == 'jinja-builtin' else (entry.kind,)
        for name in entry.names:
            for key in keys:
                payload[f'{key}:{name}'] = {
                    'name': name,
                    'kind': entry.kind,
                    'env': entry.env,
                    'display': entry.display,
                    'signature': entry.signature,
                    'summary': entry.summary,
                    'note': entry.note,
                    'example': entry.example,
                    'expect': entry.expect,
                    # A precision variant is documented by its root; say which root it came from.
                    'root': entry.name,
                }
    return {'entries': payload, 'sections': list(dict.fromkeys(e.section for e in REFERENCE))}


