r"""
What an author may type, as data: every filter, global, attribute and `meta.yaml` key, with an
example that is executed rather than asserted.

The vocabulary is **182 filters and 32 globals** on the Markdown environment alone, and it was
written down nowhere. The cost is measurable: 57 of those 182 names appear anywhere in `source/`
and the other 125 are unreachable in practice, because the only way to find one is to read
`core/builder/jinja.py`. `CLAUDE.md` covers the half-dozen conventions that have cost somebody a
bug; this covers the table.

**Docstrings could not be the source**, which is why this is a table of its own rather than a
scrape. They are written for whoever maintains the code -- `num`'s explains why it is idempotent,
`_unop`'s explains contamination -- and ten filter roots have none at all. What an author needs
is "what do I type and what comes out", which is a different text about the same function.

Three things read this:

- `docs/filters.md`, generated by `python -m core.builder.reference`. `--check` regenerates and
  exits nonzero on a difference, which is the shape `core/audit/macros.py` already has.
- the editor's `/api/reference`, which is what the hover in `tools/editor/static/app.js` shows.
- `core/tests/test_reference.py`, and that is the half that makes the rest trustworthy. One test
  asserts the table's names are *exactly* the registered ones in both directions, so a filter
  added without an entry fails the suite. Another **renders every example and compares it to the
  output written beside it**, so the document cannot drift into fiction -- which is the failure
  mode of every reference maintained by hand.

Two environments, and they are **disjoint**. `MarkdownJinjaRenderer` serves `.md` (and, through
`PictureJinjaRenderer`, `.svg` and `.tikz`); `StaticRenderer` serves `.jtex`. `|disp` is written
4760 times and works only in the first; `|upnth` is written 11 times and works only in the
second. Neither fact was written down, and either mistake is found by a failed build. Every entry
says which environment it belongs to, and the editor offers only the right set for the pane.

The examples share one small context, declared in `example_context` and printed once at the head
of the document, so an example can be read without hunting for what `v` is.
"""
from __future__ import annotations

import difflib
import sys
from dataclasses import dataclass
from pathlib import Path

#: Where the generated document lives. Relative to the repository root, like everything else
#: `core` opens by path.
DOCUMENT = Path('docs/filters.md')

#: The filter roots that `MarkdownJinjaRenderer.__generate_format_functions` gives a `0`-`9`
#: family to. Declared on the entry rather than listed here; this is only the suffix set.
PRECISIONS = tuple(str(digit) for digit in range(10))

MARKDOWN = 'markdown'
STATIC = 'static'
META = 'meta'

#: The kinds an entry may be. `filter` and `global` are checked against a live environment;
#: the rest cannot be, and are checked only for internal consistency.
KINDS = ('filter', 'global', 'attribute', 'operator', 'namespace',
         'meta-key', 'values-key', 'jinja-builtin')


@dataclass(frozen=True)
class Entry:
    """
    One name an author may write.

    `example` is a template fragment and `expect` is what it renders to, in the context
    `example_context` builds. They are a pair: the test renders the one and compares it with the
    other, so neither can go stale without the suite going red.

    An entry with no `example` is one whose output is not a string worth printing -- a `meta.yaml`
    key, or a maths global whose example would be `0.5` -- and those carry a `signature` and a
    `summary` only.
    """
    name: str
    kind: str
    summary: str
    env: str = MARKDOWN
    signature: str = ''
    example: str = ''
    expect: str = ''
    note: str = ''
    #: Whether `__generate_format_functions` also registered `<name>0` ... `<name>9`.
    precisions: bool = False
    #: Other names registered for the same object, which the coverage test must also account for.
    aliases: tuple[str, ...] = ()
    section: str = ''

    def __post_init__(self):
        assert self.kind in KINDS, f"{self.name}: unknown kind {self.kind!r}"
        assert self.env in (MARKDOWN, STATIC, META), f"{self.name}: unknown env {self.env!r}"
        assert bool(self.example) == bool(self.expect), \
            f"{self.name}: an example and its output come as a pair"

    @property
    def names(self) -> tuple[str, ...]:
        """Every name this entry accounts for: itself, its aliases, and its precision family."""
        base = (self.name, *self.aliases)
        if not self.precisions:
            return base
        return base + tuple(f'{name}{digit}' for name in base for digit in PRECISIONS)

    @property
    def display(self) -> str:
        """How the name is written at a call site: `|disp`, `PQ(...)`, `.eq`, `values:`."""
        match self.kind:
            case 'filter' | 'jinja-builtin':
                return f'|{self.name}'
            case 'attribute':
                return f'.{self.name}'
            case 'meta-key' | 'values-key':
                return f'{self.name}:'
            case 'namespace':
                return f'{self.name}.'
            case _:
                return self.name


def example_context() -> dict:
    """
    The one context every example in the table is rendered in.

    Small on purpose and printed at the head of the document, so an example reads on its own.
    The quantities are chosen to exercise the distinctions that actually catch people out: `v` is
    a given and therefore exact, `c_s` is measured and so `eq` writes `\\approx` for it, and
    `result`/`result_approx` are the pair an `answer-interval.md` spans.
    """
    from core.builder.context.quantities import (
        PhysicsConstant,
        PhysicsQuantity,
        QuantityList,
        QuantityProduct,
    )
    from core.builder.context.quantities.math import MathObject

    build = PhysicsQuantity.construct
    return {
        # A given: exact, because a statement that says 3 m/s is not approximately anything.
        'v': build(3, 'm/s', symbol='v'),
        'm': build(1.5, 'kg', symbol='m'),
        'rho': build(1000, 'kg/m^3', symbol=r'\rho'),
        'E': build(1.602176634e-19, 'J', symbol='E'),
        'd': build(5, 'km', symbol='d'),
        # Small enough that `g` still writes it out in full -- which is the case `e` exists for.
        'frac': build(1.00356e-4, '1', symbol='w'),
        'alpha': build(44.15, 'degree', symbol=r'\alpha'),
        # Measured, and shown to three figures: the shape of a `constants.yaml` entry.
        'c_s': PhysicsConstant.construct('speed_sound', magnitude=343, unit='m/s',
                                         symbol='c_s', exact=False, digits=3),
        # The pair an answer interval spans -- the exact constant and the sheet's rounding of it.
        'result': build(64.5663, 'day', symbol='t'),
        'result_approx': build(64.5665, 'day', symbol='t'),
        'sides': QuantityList(build(1, 'm'), build(2, 'm'), build(3, 'm')),
        'box': QuantityProduct(build(3, 'cm'), build(4, 'cm'), build(5, 'cm')),
        'eq': {
            'kin': MathObject('demo:kin', r'E_\text{kin} = \frac{1}{2} m v^2'),
            'chain': MathObject('demo:chain', 'a &= b \\\\\n&= c'),
            'sys': MathObject('demo:sys', 'x &+& y &=& 1 \\\\\nx &-& y &=& 0'),
        },
        # `const` as the context builds it: a namespace of measured constants, each carrying the
        # `digits:` the sheet prints it to, which is what `.approx` rounds to.
        'const': {
            'g': PhysicsConstant.construct('g', magnitude=9.80665, unit='m/s^2',
                                           symbol='g', exact=False, digits=2),
        },
        'words': {'air': 'vzduch'},
        'blocks': {'setup': 'set xlabel "t"\nset ylabel "v"'},
    }


def static_example_context() -> dict:
    """The same for `StaticRenderer`, whose vocabulary is about people and numbering."""
    import datetime
    return {
        'n': 3,
        'people': [{'name': 'Jana Nováková', 'gender': 'f'}],
        'team': ['Jana Nováková', 'Peter Novák', 'Eva Horváthová'],
        'date': datetime.date(2025, 10, 2),
    }


def render_example(entry: Entry) -> str:
    """
    What `entry.example` actually produces, through the environment the entry belongs to.

    The real renderer, not a stub: an example that passes here is one an author can paste.
    """
    from core.builder.jinja import MarkdownJinjaRenderer

    if entry.env == STATIC:
        return _render_static(entry.example)
    return MarkdownJinjaRenderer().render(entry.example, example_context())


def _render_static(template: str) -> str:
    """
    `StaticRenderer` loads from a directory, so an in-memory example needs one made for it.

    Cheaper than it looks and done once per example; the alternative is a second renderer class
    that exists only for this file.
    """
    import tempfile

    from core.builder.jinja import StaticRenderer

    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'example.jtex'
        path.write_text(template)
        return StaticRenderer(directory).render(path, static_example_context())


