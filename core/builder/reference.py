#: What the head of the document says before the table starts. Kept here rather than in a
#: template so that the generator is one file and `--check` has one thing to compare.
PREAMBLE = """\
# The Jinja vocabulary

Every filter, global, attribute and `meta.yaml` key an author may write, with an example of each.

**This file is generated.** It is written by `python -m core.builder.reference`, from the table in
`core/builder/reference.py`, and `core/tests/test_reference.py` asserts three things about it: that
the table's names are exactly the names the renderers register, in both directions; that every
example below renders to the output printed beneath it; and that this file matches what the
generator produces. So editing it by hand will be undone, and a filter added without an entry
fails the suite.

Two environments, and they are **disjoint**:

| you are editing | environment | a variable is written | and it has |
|---|---|---|---|
| `.md`, and `.svg` / `.tikz` / `.gp` | `MarkdownJinjaRenderer` | `(§ x §)` | {markdown_filters} filters, {markdown_globals} globals |
| `.jtex` | `StaticRenderer` | `(* x *)` | {static_filters} filters, {static_globals} globals |

`|disp` works only in the first and `|upnth` only in the second. Neither renderer sees the
other's table, so the mistake is found by a failed build.

A filter family written `|f0 … |f9` is one function with a precision baked in: `|f2` is `|f` to
two places, and a bare `|f` prints whatever the value has. All {generated} of those are
generated, so they behave identically and are documented once, under the root.

## The examples

Every example below is rendered in this context, which is what `example_context()` builds:

{context}

"""


def _context_table() -> str:
    """The example context, printed once so an example reads without hunting for what `v` is."""
    rows = [
        ('`v`', r'`\qty{3}{\metre\per\second}`', 'a given, so **exact**'),
        ('`m`', r'`\qty{1.5}{\kilo\gram}`', 'a given'),
        ('`d`', r'`\qty{5}{\kilo\metre}`', 'a given'),
        ('`rho`', r'`\qty{1000}{\kilo\gram\per\metre\cubed}`', r'symbol `\rho`'),
        ('`E`', r'`\qty{1.602176634e-19}{\joule}`', 'small enough to need an exponent'),
        ('`frac`', '`1.00356e-4`', "dimensionless, and the case `|e` exists for"),
        ('`alpha`', r'`\qty{44.15}{\degree}`', 'an angle'),
        ('`c_s`', r'`\qty{343}{\metre\per\second}`',
         'a **measured** constant, `digits: 3` -- so `.eq` writes `\\approx`'),
        ('`result`, `result_approx`', '`64.5663 d`, `64.5665 d`',
         'the pair an answer interval spans'),
        ('`sides`', '`QL(1 m, 2 m, 3 m)`', 'a list'),
        ('`box`', '`QP(3 cm, 4 cm, 5 cm)`', 'a product'),
        ('`eq.kin`', r'`E_\text{kin} = \frac{1}{2} m v^2`', 'a `MathObject`'),
        ('`eq.chain`', '`a &= b \\\\ &= c`', 'a chain, for `|align`'),
        ('`eq.sys`', '`x &+& y &=& 1 \\\\ x &-& y &=& 0`', 'a system, for `|arr`'),
        ('`const.g`', r'`\qty{9.80665}{\metre\per\second\squared}`',
         'measured, `digits: 2` -- so `.approx` is `9.8`'),
        ('`words.air`', '`vzduch`', 'a `words:` entry'),
        ('`n`, `team`, `people`, `date`', '`3`, three names, one author, 2025-10-02',
         'for the `.jtex` examples'),
    ]
    # A pipe inside a cell ends the cell, so `|align` has to be escaped to survive the table.
    def cell(text):
        return text.replace('|', r'\|')

    out = ['| name | value | |', '|---|---|---|']
    out += [f'| {cell(name)} | {cell(value)} | {cell(why)} |' for name, value, why in rows]
    return '\n'.join(out)


def _wrap(text: str) -> str:
    """
    Prose wrapped at the width the rest of the repository is written to.

    Worth doing although the file is generated: it is read in a terminal and in a diff, and a
    400-character paragraph is unreadable in both. Regeneration rewrites the file whole, so the
    churn a rewrap would cause in a hand-maintained file does not arise here.
    """
    import textwrap
    return '\n'.join(textwrap.wrap(text, width=100, break_long_words=False,
                                   break_on_hyphens=False))


def _block(text: str) -> str:
    """An indented code block, so an example containing a fence cannot break out of one."""
    return '\n'.join(f'    {line}' if line else '' for line in text.split('\n'))


def render_markdown() -> str:
    """The whole document, deterministically."""
    import jinja2

    from core.builder.jinja import MarkdownJinjaRenderer, StaticRenderer

    base = jinja2.Environment()
    markdown, static = MarkdownJinjaRenderer(), StaticRenderer('.')
    counts = {
        'markdown_filters': len([k for k in markdown.env.filters
                                 if k not in base.filters or k == 'e']),
        'markdown_globals': len([k for k in markdown.env.globals if k not in base.globals]),
        'static_filters': len([k for k in static.env.filters if k not in base.filters]),
        'static_globals': len([k for k in static.env.globals if k not in base.globals]),
        'generated': sum(len(PRECISIONS) * len((e.name, *e.aliases))
                         for e in REFERENCE if e.precisions),
    }

    out = [PREAMBLE.format(context=_context_table(), **counts)]
    section = None
    for entry in REFERENCE:
        if entry.section != section:
            section = entry.section
            out.append(f'## {section}\n')

        heading = f'`{entry.display}`'
        if entry.precisions:
            heading += f' · `{entry.display}0` … `{entry.display}9`'
        out.append(f'### {heading}\n')
        # The signature earns a line only when it says more than the heading already does --
        # which it does for everything that takes an argument, and for nothing that does not.
        if entry.signature and entry.signature != entry.display:
            out.append(f'`{entry.signature}`\n')
        out.append(_wrap(entry.summary) + '\n')
        if entry.note:
            out.append(_wrap(entry.note) + '\n')
        if entry.example:
            out.append(_block(entry.example))
            out.append('\nproduces\n')
            out.append(_block(entry.expect))
            out.append('')

    return '\n'.join(out).rstrip('\n') + '\n'


# ------------------------------------------------------------------------------ CLI

def main():
    """
    `python -m core.builder.reference` -- write `docs/filters.md`; `--check` compares instead.

    The same shape as `core/audit/macros.py`: run it to refresh, run it with `--check` in CI.
    """
    import argparse

    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='compare against the file on disk; exit 1 if it is stale')
    args = parser.parse_args()

    generated = render_markdown()
    if not args.check:
        DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
        DOCUMENT.write_text(generated)
        print(f'{DOCUMENT}: {len(REFERENCE)} entries, '
              f'{len({n for e in REFERENCE for n in e.names})} names')
        raise SystemExit(0)

    if not DOCUMENT.is_file():
        print(f'{DOCUMENT} has never been generated')
        raise SystemExit(1)
    current = DOCUMENT.read_text()
    if current == generated:
        print(f'{DOCUMENT} is up to date')
        raise SystemExit(0)

    diff = difflib.unified_diff(current.splitlines(), generated.splitlines(),
                                fromfile=f'{DOCUMENT} (on disk)', tofile='(generated)', lineterm='')
    print(f'{DOCUMENT} is stale; run `python -m core.builder.reference`')
    for line in diff:
        print(line, file=sys.stderr)
    raise SystemExit(1)


if __name__ == '__main__':
    main()
